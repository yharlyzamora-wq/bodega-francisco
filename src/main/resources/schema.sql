-- Esquema en SQL estandar (H2). Se ejecuta en cada arranque: todo es idempotente.

CREATE TABLE IF NOT EXISTS categoria (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  apellido VARCHAR(80) NOT NULL,
  correo VARCHAR(120) NOT NULL UNIQUE,
  celular VARCHAR(15),
  password_hash VARCHAR(100) NOT NULL,
  rol VARCHAR(10) DEFAULT 'CLIENTE' NOT NULL CHECK (rol IN ('CLIENTE','PERSONAL','ADMIN')),
  activo BOOLEAN DEFAULT TRUE NOT NULL,
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS producto (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(12) NOT NULL UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  categoria_id INT NOT NULL REFERENCES categoria(id),
  precio DECIMAL(10,2) NOT NULL CHECK (precio >= 0),
  stock INT DEFAULT 0 NOT NULL CHECK (stock >= 0),
  activo BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS pedido (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuario(id),
  personal_id INT REFERENCES usuario(id),
  modalidad VARCHAR(10) NOT NULL CHECK (modalidad IN ('RECOJO','DELIVERY')),
  direccion VARCHAR(200),
  costo_delivery DECIMAL(10,2) DEFAULT 0 NOT NULL,
  total DECIMAL(10,2) NOT NULL,
  estado VARCHAR(15) DEFAULT 'PENDIENTE' NOT NULL
    CHECK (estado IN ('PENDIENTE','CONFIRMADO','EN_PREPARACION','LISTO','ENTREGADO','CANCELADO')),
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INT NOT NULL REFERENCES pedido(id),
  producto_id INT NOT NULL REFERENCES producto(id),
  cantidad INT NOT NULL CHECK (cantidad > 0),
  precio_unitario DECIMAL(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS pago (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INT NOT NULL REFERENCES pedido(id),
  metodo VARCHAR(10) NOT NULL CHECK (metodo IN ('YAPE','PLIN','TARJETA')),
  monto DECIMAL(10,2) NOT NULL,
  estado VARCHAR(10) DEFAULT 'PENDIENTE' NOT NULL CHECK (estado IN ('PENDIENTE','VALIDADO','RECHAZADO')),
  referencia VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS reclamo (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuario(id),
  pedido_id INT REFERENCES pedido(id),
  asunto VARCHAR(120) NOT NULL,
  descripcion VARCHAR(2000) NOT NULL,
  estado VARCHAR(10) DEFAULT 'ABIERTO' NOT NULL CHECK (estado IN ('ABIERTO','RESPONDIDO','CERRADO')),
  respuesta VARCHAR(2000),
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS movimiento_stock (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INT NOT NULL REFERENCES producto(id),
  usuario_id INT REFERENCES usuario(id),
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA','SALIDA','AJUSTE')),
  cantidad INT NOT NULL,
  motivo VARCHAR(120),
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

